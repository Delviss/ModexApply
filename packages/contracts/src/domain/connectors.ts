/**
 * Inbound webhooks are signed, and the signature covers a timestamp.
 *
 * Without the timestamp in the signed material, a captured request is valid
 * forever and "replay-safe" means only "we store the event id" — which stops a
 * duplicate but not an attacker replaying a six-month-old `offer_made` at a
 * moment of their choosing. The event id and the window are both needed, and
 * they stop different things.
 */
export const WEBHOOK_TOLERANCE_SECONDS = 300;

/**
 * The signed material: timestamp, a separator, then the raw body exactly as it
 * arrived. Signing a re-serialised body would mean a partner's key ordering
 * could change the signature without changing the request.
 *
 * Signing and verification themselves live in `@modex/contracts/node` — they
 * need `node:crypto`, and this module is compiled into browser bundles.
 */
export function webhookSigningPayload(timestamp: string, rawBody: string): string {
  return `${timestamp}.${rawBody}`;
}

/**
 * Per-partner poll budget for connectors with no webhooks. Rate limiting is a
 * property of the partner's configuration, not of our convenience: a university
 * that asks for one call a minute gets one call a minute.
 */
export const DEFAULT_POLL_INTERVAL_SECONDS = 900;
export const MIN_POLL_INTERVAL_SECONDS = 60;
